"""Observed type families and pairings across the measured homepages, with whether each family is available under an
open licence on google/fonts (OFL, Apache or UFL directories). Writes skills/startup-landing-design/references/type-observed.md.

Usage: python3 scripts/summarize_type.py [--check] [--gfonts <path to a google/fonts checkout or its family list file>]
The family list is cached in research/google-fonts-families.txt so the check does not need the checkout.
"""
import json, re, sys, subprocess
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'skills/startup-landing-design/references/type-observed.md'
CACHE = ROOT / 'research/google-fonts-families.txt'

def slug(name): return re.sub(r'[^a-z0-9]', '', name.lower())

# Families on google/fonts, by slug, with the licence directory.
if '--gfonts' in sys.argv:
    src = Path(sys.argv[sys.argv.index('--gfonts') + 1])
    tree = subprocess.run(['git', '-C', str(src), 'ls-tree', '--name-only', 'HEAD', 'ofl/', 'apache/', 'ufl/'], capture_output=True, text=True).stdout.split()
    CACHE.write_text('\n'.join(sorted(tree)) + '\n')
gf = {}
for line in CACHE.read_text().split():
    lic, fam = line.split('/')
    gf[fam] = {'ofl': 'SIL OFL', 'apache': 'Apache-2.0', 'ufl': 'UFL'}[lic]

SYSTEM = {'ui-monospace', 'ui-sans-serif', 'ui-serif', 'system-ui', '-apple-system', 'blinkmacsystemfont', 'arial', 'helvetica', 'helvetica neue', 'times new roman', 'georgia', 'segoe ui', 'roboto', 'sans-serif', 'serif', 'monospace'}
ALIAS = {'inter variable': 'inter', 'inter display': 'inter', 'inter tight': 'intertight', 'geist sans': 'geist', 'ibm plex sans var': 'ibmplexsans'}

def norm(f):
    f = (f or '').strip().strip('"\'')
    key = ALIAS.get(f.lower(), slug(f))
    return f, key

def licence(key, raw):
    if raw.lower() in SYSTEM: return 'system'
    return gf.get(key, 'proprietary or self-hosted')

rows = []
for f, tier in [('research/measurements.jsonl', 'cohort'), ('research/measurements-reference.jsonl', 'reference')]:
    for line in (ROOT / f).open():
        r = json.loads(line)
        if r['error'] or 'desktop' not in r['viewports']: continue
        d = r['viewports']['desktop']
        rows.append({'id': r['id'], 'tier': tier, 'h1': d.get('h1_family') or d.get('display_family'), 'body': d.get('body_family'), 'fams': d.get('families', [])})
n = len(rows)

fam_count = Counter()
for r in rows:
    for x in dict.fromkeys(norm(f)[1] for f in r['fams'][:2]):
        fam_count[x] += 1
names = {}
for r in rows:
    for f in r['fams'][:2]:
        raw, key = norm(f); names.setdefault(key, raw)

pair_count = Counter()
for r in rows:
    if r['h1'] and r['body']:
        h, b = norm(r['h1'])[1], norm(r['body'])[1]
        pair_count[(h, b)] += 1
same = sum(c for (h, b), c in pair_count.items() if h == b)
paired = sum(pair_count.values())

def pct(x): return f'{round(100 * x / n)}%'
lines = ['# Observed type', '',
         f'Generated by `scripts/summarize_type.py` from the measured homepages ({n} pages: cohort and reference tier, 2026-10-19/20). A family counts once per page when it is the first or second most-used family. "Open licence" means the family is published on google/fonts under the SIL OFL, Apache-2.0 or UFL; a proprietary family is listed so you know what the page used, not so you copy it.', '',
         'Use this to pick faces with evidence behind them, and to avoid the ones everyone uses unless you have a reason (TY-10).', '',
         '## Most used families', '', '| Family | Pages | Share | Licence |', '| --- | --- | --- | --- |']
for key, c in fam_count.most_common(30):
    raw = names[key]
    lines.append(f'| {raw} | {c} | {pct(c)} | {licence(key, raw)} |')
lines += ['', '## Headline and body pairings', '',
          f'Of {paired} pages with a measurable headline and body family, {same} ({round(100 * same / paired)}%) use one family for both. The pairings below are the most common two-family combinations.', '',
          '| Headline | Body | Pages |', '| --- | --- | --- |']
for (h, b), c in pair_count.most_common(40):
    if h != b and c >= 2:
        lines.append(f'| {names.get(h, h)} | {names.get(b, b)} | {c} |')
open_share = sum(c for k, c in fam_count.items() if licence(k, names[k]) not in ('system', 'proprietary or self-hosted'))
sys_share = sum(c for k, c in fam_count.items() if licence(k, names[k]) == 'system')
lines += ['', '## What this says', '',
          f'- Open-licence families account for {round(100 * open_share / sum(fam_count.values()))}% of first-or-second families; system stacks for {round(100 * sys_share / sum(fam_count.values()))}%; the rest are proprietary or self-hosted custom faces.',
          f'- Inter alone is on {pct(fam_count.get("inter", 0))} of pages and Geist on {pct(fam_count.get("geist", 0))}: both read as default. A monospace face as the second family is common on developer pages and is a role, not decoration.',
          '- A serif display over a sans body is rare in this sample; where it appears it is a deliberate editorial or consumer choice, which is why TY-10 and CO-03 ask for the reason.',
          '- Families are computed stacks as rendered, not verified licences; confirm the licence of any face before shipping it.']
text = '\n'.join(lines) + '\n'
if '--check' in sys.argv:
    sys.exit(0 if OUT.exists() and OUT.read_text() == text else 1)
OUT.write_text(text)
print(f'{n} pages, {len(fam_count)} families, {paired} pairings')
